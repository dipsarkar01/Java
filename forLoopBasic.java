public class forLoopBasic {
    public static void main(String[] args){
        for (int i = 0; i <= 20; i++){
            System.out.print(i + " ");
        }
        System.out.print("\n");
        for (int a = 20; a >= 0; a--) {
            System.out.print(a + " ");
        }
        System.out.print("\n");
        for (int i = 0; i <= 20; i++) {
            System.out.print(i+"Dip"+" ");
        }
    }
}