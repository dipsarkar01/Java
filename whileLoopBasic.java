public class whileLoopBasic {
    public static void main(String[] args) {
        int i = 0, j = 10;
        while (i <= 10) {
            System.out.print(i + " ");
            i++;
        }
        System.out.print("\n");
        while (j >= 0) {
            System.out.print(j + " ");
            j--;
        }
    }
}